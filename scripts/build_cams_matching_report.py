"""Report how archived CAMS forecasts are matched to stations, and how far the archive is from a usable fold.

    python -m scripts.build_cams_matching_report

Reads only development artefacts (the guarded join excludes the sealed final
test by construction). Writes docs/research/CAMS_STATION_MATCHING_REPORT.md and
results/research/cams_station_matching_report.json. No outcome value is read:
only whether a station-day target is valid, which the join already records.
"""
from __future__ import annotations

import json
from datetime import date, timedelta
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results/research"


def read(name):
    return json.loads((RES / name).read_text(encoding="utf-8"))


def main():
    from src.research.calibration.protocol import load
    from src.research.calibration.splits import calendar, rolling_folds

    protocol = load()
    join = read("cams_station_join_manifest.json")
    alignment = read("cams_development_alignment.json")
    baseline = read("cams_raw_baseline_derivation.json")
    acquisition = read("cams_development_acquisition.json")
    plan = read("cams_development_acquisition_plan.v2.json")
    minimum = protocol["stations"]["minimum_valid_target_days"]

    frame = pd.read_parquet(ROOT / alignment["table"], columns=["station_id", "target_date", "target_valid"])
    per_station = frame[frame.target_valid].groupby("station_id").size()
    valid_share = float(frame.target_valid.mean())

    # Which archive month each fold needs, and whether its training window can reach the station minimum.
    folds = []
    for fold in rolling_folds(calendar(protocol), protocol):
        if fold["role"] == "final_test":
            continue
        needed_through = date.fromisoformat(fold["test_range"][1]) - timedelta(days=1)  # forecasts are issued the day before
        folds.append({"fold": fold["name"], "train_days": len(fold["train"]), "train_range": fold["train_range"],
                      "test_range": fold["test_range"], "cams_needed_through": str(needed_through),
                      "expected_valid_days_per_station": round(len(fold["train"]) * valid_share),
                      "can_meet_station_minimum": round(len(fold["train"]) * valid_share) >= minimum})
    first = next((f for f in folds if f["can_meet_station_minimum"]), None)

    group = {j["id"]: j["group"] for j in plan["jobs"]}
    months = {}
    for job in plan["jobs"]:
        month = job["request"]["date"][0][:7]
        months.setdefault(month, {})[group[job["id"]]] = (acquisition["jobs"].get(job["id"]) or {}).get("status", "NOT_SUBMITTED")
    paired = [m for m, s in months.items() if set(s.values()) == {"VERIFIED_GRIB"}]
    files_needed = None
    if first:
        cutoff = first["cams_needed_through"][:7]
        files_needed = sum(1 for m, s in months.items() if m <= cutoff for v in s.values() if v != "VERIFIED_GRIB")

    report = {
        "generated_by": "scripts/build_cams_matching_report.py",
        "join": {k: join.get(k) for k in ("rows", "stations", "cities", "dates", "exact_targets", "censored_severe_retained",
                                          "rejected_targets_retained", "availability_violations", "missing_cams_dates", "date_range", "sha256")},
        "raw_cams_station_days": baseline.get("rows"), "raw_cams_stations": baseline.get("stations"),
        "matching": {"grid": "CAMS operational 0.4-degree grid", "rule": "nearest grid centre (station latitude and longitude each rounded to the 0.4-degree lattice); the cell must exist exactly once in the file",
                     "time": "native 3-hourly leads interpolated to hourly within the acquired leads; no extrapolation",
                     "coastal_handling": "none: a coastal station can fall in a cell that is mostly sea; not yet audited"},
        "valid_target_share": round(valid_share, 3),
        "valid_days_per_station": {"max": int(per_station.max()), "median": int(per_station.median()), "minimum_required": minimum},
        "paired_months_verified": paired, "folds": folds, "first_fold_that_can_qualify": first,
        "files_still_needed_for_that_fold": files_needed,
    }
    (RES / "cams_station_matching_report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")

    j = report["join"]
    lines = [
        "# CAMS-to-station matching report",
        "",
        "Generated by `scripts/build_cams_matching_report.py` from the guarded development join; regenerate after each archive update. "
        "Machine-readable: `results/research/cams_station_matching_report.json`. The sealed final test (10 July to 7 October 2026) is outside the join by construction.",
        "",
        "## Current join",
        "",
        "| Item | Value |", "| --- | --- |",
        f"| Station-days | {j['rows']:,} ({j['stations']} stations, {j['cities']} cities) |",
        f"| Target dates | {j['dates']} ({j['date_range'][0]} to {j['date_range'][1]}) |",
        f"| Exact targets | {j['exact_targets']:,} |",
        f"| Censored Severe targets (lower bound only) | {j['censored_severe_retained']} |",
        f"| Rejected targets kept visible | {j['rejected_targets_retained']:,} |",
        f"| Temporal availability violations | **{j['availability_violations']}** |",
        f"| Plan dates without CAMS yet | {j['missing_cams_dates']} |",
        f"| Join hash | `{j['sha256'][:16]}` |",
        "",
        "## How a station is matched",
        "",
        f"- **Space**: {report['matching']['rule']}. Grid: {report['matching']['grid']}.",
        f"- **Time**: {report['matching']['time']}. Forecasts are 00 UTC runs issued the day before the target; observations obey the 20:00 IST cutoff.",
        f"- **Coast**: {report['matching']['coastal_handling']}.",
        "",
        "## Distance to the first usable fold",
        "",
        f"The protocol needs {minimum} valid training days per station. In the current join a station has at most "
        f"{report['valid_days_per_station']['max']} (median {report['valid_days_per_station']['median']}), and {report['valid_target_share']:.0%} of station-days have a valid target. "
        "Expanding folds grow by 30 days, so early folds cannot qualify whatever the archive holds.",
        "",
        "| Fold | Training days | Training ends | Test window | CAMS needed through | Expected valid days per station | Can qualify |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for f in folds:
        lines.append(f"| {f['fold']} | {f['train_days']} | {f['train_range'][1]} | {f['test_range'][0]} to {f['test_range'][1]} | {f['cams_needed_through']} | "
                     f"{f['expected_valid_days_per_station']} | {'yes' if f['can_meet_station_minimum'] else 'no'} |")
    lines += ["",
              (f"**First fold that can qualify: {first['fold']}**, which needs CAMS through {first['cams_needed_through']}. "
               f"{files_needed} archive files up to that month are not yet verified." if first else "No fold can qualify under the current valid-target share."),
              "This is an expectation from the average valid share, not a guarantee for every station.", ""]
    (ROOT / "docs/research/CAMS_STATION_MATCHING_REPORT.md").write_text("\n".join(lines), encoding="utf-8")
    print(json.dumps({"first_fold": first and first["fold"], "files_needed": files_needed, "paired_months": len(paired)}))


if __name__ == "__main__":
    main()
