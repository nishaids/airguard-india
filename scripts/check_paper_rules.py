"""Check the manuscript against the call's format rules, without compiling it.

Most of Part E is checkable statically: which document class, that hyperref is
absent, that no page style is set, that every figure is a vector PDF that
exists, that every table is generated rather than typed, and that every citation
key resolves to a verified bibliography entry. Page count and embedded fonts are
not: those need a LaTeX run, and this environment has no TeX toolchain, so they
are reported as unchecked rather than assumed.

    python -m scripts.check_paper_rules

Exits non-zero when a rule fails, so CI can hold the line once a toolchain
exists. Unchecked rules do not fail the run but are always listed.
"""
import json
import re
import shutil
import sys
from datetime import datetime, timezone

from src import config

PAPER = config.PROJECT_ROOT / 'paper'
MAIN = PAPER / 'main.tex'
FORBIDDEN_PACKAGES = ('hyperref', 'fancyhdr')
PAGE_STYLE = re.compile(r'\\(?:pagestyle|thispagestyle|pagenumbering)\b')


def main():
    if not MAIN.exists():
        print('paper/main.tex is missing.')
        return 1
    text = MAIN.read_text(encoding='utf-8')
    bib_path = PAPER / 'refs.bib'
    bib = bib_path.read_text(encoding='utf-8') if bib_path.exists() else ''
    verification = {}
    report_path = config.PROJECT_ROOT / 'results/reference_verification.json'
    if report_path.exists():
        verification = json.loads(report_path.read_text(encoding='utf-8'))

    cited = sorted({key.strip() for group in re.findall(r'\\cite\{([^}]*)\}', text)
                    for key in group.split(',') if key.strip()})
    defined = sorted(set(re.findall(r'^@\w+\{([^,]+),', bib, re.MULTILINE)))
    verified_keys = {entry['key'] for entry in verification.get('verified_entries', [])}
    figures = re.findall(r'\\includegraphics(?:\[[^\]]*\])?\{([^}]*)\}', text)
    inputs = re.findall(r'\\input\{([^}]*)\}', text)

    checks = {
        'ieee_conference_class': bool(re.search(r'\\documentclass\[[^\]]*conference[^\]]*\]\{IEEEtran\}', text)),
        'no_clickable_links': not any(re.search(rf'\\usepackage(?:\[[^\]]*\])?\{{{package}\}}', text)
                                      for package in FORBIDDEN_PACKAGES),
        'no_page_style_override': not PAGE_STYLE.search(text),
        'every_figure_is_an_existing_pdf': all(
            (PAPER / name).suffix.lower() == '.pdf' and (PAPER / name).exists() for name in figures),
        'every_table_is_generated': all(
            (PAPER / name).exists() and 'Generated by' in (PAPER / name).read_text(encoding='utf-8')
            for name in inputs),
        'bibliography_is_generated': 'Generated by scripts/build_refs.py' in bib,
        'every_citation_resolves': bool(cited) and all(key in defined for key in cited),
        'every_citation_was_verified': bool(cited) and all(key in verified_keys for key in cited),
        'no_dropped_reference_is_cited': not (set(cited) & {entry['key'] for entry in
                                                            verification.get('dropped_entries', [])}),
        'ai_use_disclosed_in_acknowledgment': 'AI use disclosure' in text,
        'ethics_statement_present': 'Ethics Statement' in text,
        'authors_resolved': 'NAME' not in re.search(r'\\author\{.*?\}\}', text, re.S).group(0)
        if re.search(r'\\author\{.*?\}\}', text, re.S) else False,
    }
    unchecked = {
        'page_count_at_most_six': 'needs a LaTeX run; no TeX toolchain is installed here',
        'fonts_embedded': 'needs pdffonts on a compiled PDF',
        'figure_text_at_least_8pt': 'needs a compiled PDF to measure',
        'similarity_check': 'venue tool; run before submission',
        'paper_size_per_cfp': 'no conference has been chosen (HUMAN_ACTIONS.md)',
    }

    failed = sorted(name for name, value in checks.items() if not value)
    summary = {
        'generated_at': datetime.now(timezone.utc).isoformat(),
        'latex_toolchain': shutil.which('pdflatex') or shutil.which('latexmk'),
        'citations': cited, 'bibliography_entries': len(defined),
        'figures': figures, 'generated_tables': inputs,
        'checks': checks, 'failed': failed, 'unchecked': unchecked,
        'submission_ready': False,
        'submission_blockers': sorted(set(failed) | {
            'empirical results are pending', 'no conference chosen', 'author details unresolved'}),
    }
    (config.PROJECT_ROOT / 'results/paper_rules.json').write_text(
        json.dumps(summary, indent=1), encoding='utf-8')
    for name, value in checks.items():
        print(f"{'PASS' if value else 'FAIL'} {name}")
    for name, reason in unchecked.items():
        print(f"SKIP {name}: {reason}")
    print(json.dumps({'failed': failed, 'citations': len(cited),
                      'bibliography_entries': len(defined)}, indent=1))
    return 1 if failed else 0


if __name__ == '__main__':
    sys.exit(main())
