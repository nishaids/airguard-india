"""Generate paper/tables/evidence.tex from the committed coverage artefacts.

The previous version of this table was typed by hand, which breaks the project's
first rule: every number in the paper comes from a committed script reading
versioned data. Each row below names the artefact and key it was read from, so a
reader can check any figure, and a missing artefact prints an em dash rather
than a stale number.
"""
import json
import sys
from datetime import datetime, timezone

from src import config

ROWS = [
    ('Measured hourly records audited', 'results/data_coverage.json', 'measured_rows_audited'),
    ('Eligible issue-time forecast/target pairs', 'results/data_coverage.json', 'eligible_paired_rows'),
    ('Stations with 365 candidate complete days', 'results/data_coverage.json',
     'stations_with_365_complete_candidate_days'),
    ('Archive hourly records collected', 'results/archive_coverage.json', 'rows'),
    ('Station-days with a valid CPCB-style daily AQI', 'results/archive_coverage.json',
     'station_days_with_valid_daily_aqi'),
    ('Stations with one year of valid daily targets', 'results/archive_coverage.json',
     'stations_with_one_year_of_valid_targets'),
    ('Fixed-time prospective forecasts issued', 'results/release/database_audit.json', 'counts.research_forecast_runs'),
    ('Verified prospective outcomes', 'results/release/database_audit.json',
     'counts.research_forecast_verifications'),
]


def dig(payload, path):
    value = payload
    for part in path.split('.'):
        if not isinstance(value, dict) or part not in value:
            return None
        value = value[part]
    return value


def main():
    rows, provenance = [], []
    for label, artefact, key in ROWS:
        path = config.PROJECT_ROOT / artefact
        value = dig(json.loads(path.read_text(encoding='utf-8')), key) if path.exists() else None
        rows.append((label, '--' if value is None else f'{value:,}' if isinstance(value, int) else str(value)))
        provenance.append({'label': label, 'artefact': artefact, 'key': key, 'value': value})

    lines = [
        '% Generated by scripts/export_evidence_table.py. Do not edit by hand.',
        f'% Generated {datetime.now(timezone.utc).isoformat()} from the artefacts named in each row.',
        '\\begin{table}[t]',
        '\\caption{Evidence actually held. Record counts do not establish predictive skill, and a',
        'station-year of a single pollutant cannot produce a CPCB daily AQI.}',
        '\\label{tab:evidence}',
        '\\centering',
        '\\begin{tabular}{lr}',
        '\\toprule',
        'Evidence & Count \\\\',
        '\\midrule',
    ]
    lines += [f'{label} & {value} \\\\' for label, value in rows]
    lines += ['\\bottomrule', '\\end{tabular}', '\\end{table}', '']
    out = config.PROJECT_ROOT / 'paper/tables/evidence.tex'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(lines), encoding='utf-8')
    (config.PROJECT_ROOT / 'results/paper_tables.json').write_text(json.dumps({
        'generated_at': datetime.now(timezone.utc).isoformat(),
        'tables': {'paper/tables/evidence.tex': provenance},
    }, indent=1), encoding='utf-8')
    print(json.dumps({'table': config.portable(out), 'rows': provenance}, indent=1))
    return 0


if __name__ == '__main__':
    sys.exit(main())
