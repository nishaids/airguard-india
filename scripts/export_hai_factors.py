"""Generate the HAI v2 factor table for the paper, and refresh its artefacts.

The table is generated so the manuscript cannot drift from the register: every
row states whether the coefficient is adopted, neutral by declaration, or still
awaiting review, and no row can show a number the register does not hold.
"""
import json
import sys

from src import config
from src.features.hai_v2 import load_factors, register_summary


def escape(text):
    out = str(text)
    for character, replacement in (('\\', r'\textbackslash{}'), ('&', r'\&'), ('%', r'\%'),
                                   ('_', r'\_'), ('#', r'\#'), ('$', r'\$')):
        out = out.replace(character, replacement)
    return out


def coefficient_rows(register):
    rows = []
    for pollutant, entry in (register.get('coefficients') or {}).items():
        if entry.get('neutral'):
            state = 'Neutral by declaration'
        elif entry.get('verified') and entry.get('value') is not None:
            state = f"{entry['value']:.6g} ({entry.get('unit', '')})"
        else:
            state = 'Awaiting evidence review'
        citation = entry.get('citation')
        rows.append((pollutant, escape(entry.get('exposure_window') or '--'), escape(state),
                     f"\\cite{{{citation}}}" if citation and entry.get('verified') else '--'))
    return rows


def table(register):
    lines = [
        '% Generated by scripts/export_hai_factors.py. Do not edit by hand.',
        '\\begin{table}[t]',
        '\\caption{HAI v2 coefficient register. No concentration--response coefficient is adopted:',
        'each entry awaits verification of its source, exposure window, population and units.}',
        '\\label{tab:hai_factors}',
        '\\centering',
        '\\begin{tabular}{llll}',
        '\\toprule',
        'Pollutant & Window & Coefficient & Source \\\\',
        '\\midrule',
    ]
    for pollutant, window, state, citation in coefficient_rows(register):
        lines.append(f'{escape(pollutant)} & {window} & {state} & {citation} \\\\')
    lines += ['\\midrule', '\\multicolumn{4}{l}{\\footnotesize Cohort effect-modification factors} \\\\', '\\midrule']
    for cohort, entry in (register.get('cohorts') or {}).items():
        factors = entry.get('factors') or {}
        neutral = all(float(value) == 1.0 for value in factors.values())
        state = 'all factors 1.0 (no evidence adopted)' if neutral else 'see register'
        role = 'reference' if entry.get('reference') else ('verified' if entry.get('verified') else 'unverified')
        lines.append(f'{escape(cohort.replace("_", " "))} & {role} & {escape(state)} & -- \\\\')
    lines += ['\\bottomrule', '\\end{tabular}', '\\end{table}', '']
    return '\n'.join(lines)


def main():
    register = load_factors()
    summary = register_summary(register)
    out = config.PROJECT_ROOT / 'paper/tables/hai_factors.tex'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(table(register), encoding='utf-8')

    # The result artefacts stay PENDING while the register adopts nothing, and
    # say which coefficients are missing rather than only that something is.
    pending = {
        'status': 'PENDING', 'accepted': False, 'metrics': None,
        'register_status': register.get('status'), 'awaiting_review': register.get('awaiting_review'),
        'neutral_by_declaration': register.get('neutral'), 'reviewer': register.get('reviewer'),
        'framework': 'src/features/hai_v2.py', 'register': 'config/hai_factors.yaml',
        'generated_table': 'paper/tables/hai_factors.tex',
    }
    for name, reason in (
            ('hai_v2', 'Verified coefficients/exposure definitions and human evidence review required. '
                       'The index framework, scale anchoring and cohort register exist and are tested.'),
            ('hai_sensitivity', 'Monte Carlo over coefficient confidence intervals requires published '
                                'intervals to sample from. The harness exists and separates the '
                                'aggregation effect from the vulnerability effect.')):
        path = config.PROJECT_ROOT / f'results/{name}.json'
        path.write_text(json.dumps({**pending, 'reason': reason, 'summary': summary}, indent=1),
                        encoding='utf-8')
    print(json.dumps({'table': config.portable(out), 'usable': summary['usable'],
                      'awaiting_review': summary['awaiting_review']}, indent=1))
    return 0


if __name__ == '__main__':
    sys.exit(main())
