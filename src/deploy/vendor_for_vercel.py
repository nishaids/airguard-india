"""Bundle everything the Vercel Python functions need into ``webapp/``.

Why this exists
----------------
The Vercel CLI uploads the directory it is run from, and the project's Root
Directory is ``webapp``. The two Python functions, however, import ``src`` and
``app.utils`` and read data files that live *above* ``webapp``. Vercel's
"include files outside the Root Directory" setting exists for exactly this, but
it is a dashboard-only project setting with no CLI flag, so relying on it would
make the deployment depend on a checkbox that is invisible to this repository.

Instead this script mirrors the handful of paths those functions actually touch
into ``webapp/api/_bundle/``, preserving the repository's own directory layout.
That matters: ``config.PROJECT_ROOT`` is ``Path(__file__).resolve().parents[1]``,
so a copy of ``src/config.py`` at ``_bundle/src/config.py`` makes
``PROJECT_ROOT`` resolve to ``_bundle/`` and every ``DATA_DIR`` / ``MODELS_DIR``
/ ``RESULTS_DIR`` path follows automatically, with no code changes.

``src/`` remains the single source of truth. ``_bundle/`` is generated output,
regenerated by this script and refreshed before every deploy.

The two largest files are gzipped on the way in (34 MB of feature matrix and
28 MB of exported trees become roughly 10 MB in total), which keeps the upload
small; ``serverless_inference.py`` reads either form.

Run with::

    python -m src.deploy.vendor_for_vercel
"""

from __future__ import annotations

import gzip
import shutil
from pathlib import Path

from src import config

VENDOR = config.PROJECT_ROOT / "webapp" / "api" / "_bundle"

#: Python packages the functions import. Copied wholesale, minus caches.
PACKAGE_DIRS = ["src", "app"]

#: Files copied as they are.
PLAIN_FILES = [
    "data/processed/feature_columns.json",
    "results/safe_windows.json",
    "models/deploy/regression_booster.json",
    "models/deploy/classification_classes.json",
    "models/deploy/feature_order.json",
    "models/deploy/live_reference.json",
]

#: Files large enough to be worth gzipping. The readers accept either form.
GZIP_FILES = [
    "data/processed/features_full.csv",
    "data/processed/city_day_clean.csv",
    "models/deploy/classification_booster.json",
]


def _ignore(_dir: str, names: list[str]) -> set[str]:
    ignored = {n for n in names if n == "__pycache__" or n.endswith(".pyc")}
    # The live server uses the prospective ledger, never offline archive/model
    # development. Keep those research entry points out of the deployed bundle.
    if Path(_dir).resolve() == (config.PROJECT_ROOT / "src" / "research").resolve():
        ignored.add("calibration")
    return ignored


def main() -> None:
    expected = (config.PROJECT_ROOT / 'webapp' / 'api' / '_bundle').resolve()
    if VENDOR.resolve() != expected or not expected.is_relative_to(config.PROJECT_ROOT.resolve()):
        raise ValueError('Refusing to replace a bundle outside the expected workspace path')
    if VENDOR.exists():
        shutil.rmtree(VENDOR)
    VENDOR.mkdir(parents=True)

    for package in PACKAGE_DIRS:
        shutil.copytree(config.PROJECT_ROOT / package, VENDOR / package, ignore=_ignore)

    for relative in PLAIN_FILES:
        destination = VENDOR / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(config.PROJECT_ROOT / relative, destination)

    for relative in GZIP_FILES:
        source = config.PROJECT_ROOT / relative
        destination = VENDOR / (relative + ".gz")
        destination.parent.mkdir(parents=True, exist_ok=True)
        with source.open("rb") as raw, gzip.open(destination, "wb", compresslevel=6) as packed:
            shutil.copyfileobj(raw, packed)

    (VENDOR / ".gitattributes").write_text("* -diff\n", encoding="utf-8")

    total = sum(f.stat().st_size for f in VENDOR.rglob("*") if f.is_file())
    print(f"vendored into {VENDOR.relative_to(config.PROJECT_ROOT)}")
    print(f"  packages : {', '.join(PACKAGE_DIRS)}")
    print(f"  files    : {len(PLAIN_FILES)} plain, {len(GZIP_FILES)} gzipped")
    print(f"  total    : {total / 1e6:.1f} MB")


if __name__ == "__main__":
    main()

