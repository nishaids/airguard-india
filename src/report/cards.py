"""Generation of the responsible-AI artefacts: the data card and the model card.

Both documents are generated from ``results/*.json`` and
``data/raw/PROVENANCE.json``, so every figure they quote was produced by executed
code. The limitations sections are written out in full rather than summarised,
because a limitation that is not stated plainly is not disclosed.

Outputs
-------
``reports/data_card.md``
``reports/model_card.md``
``models/model_card.md`` (a copy beside the artefacts it describes)

Run with::

    python -m src.report.cards
"""

from __future__ import annotations

