DATA_CARD = config.REPORTS_DIR / "data_card.md"
MODEL_CARD = config.REPORTS_DIR / "model_card.md"
MODEL_CARD_COPY = config.MODELS_DIR / "model_card.md"


def _load(name: str, directory: Path = config.RESULTS_DIR) -> Dict[str, Any]:
    path = directory / name
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


