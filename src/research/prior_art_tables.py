"""Render the prior-art corpus into the tables the blueprint cites.

``docs/airguard2/prior_art.json`` is the single place a reviewed system is
described. This turns it into a capability matrix and a limitations table for
the blueprint, and into a CSV with every field for anyone who wants to sort or
filter the corpus in a spreadsheet. Nothing is typed into the document twice.

Run with::

    python -m src.research.prior_art_tables
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

from src import config

DOCS = config.PROJECT_ROOT / "docs" / "airguard2"
SOURCE = DOCS / "prior_art.json"
OUT_MD = DOCS / "_generated" / "prior_art_tables.md"
OUT_CSV = DOCS / "prior_art_corpus.csv"

LABELS = {
    "live": "Live",
    "forecast": "Fore-cast",
    "weather": "Wea-ther",
    "subcity": "Sub-city",
    "uncertainty": "Uncer-tainty",
    "cohort": "Cohort advice",
    "advice_from_forecast": "Advice from forecast",
    "exposure_window": "Exposure window",
    "explanation": "Expla-nation",
    "scenario": "Scen-ario",
    "trust": "Trust / abstain",
    "unseen_city": "Unseen city",
    "open": "Open",
}
SYMBOL = {"Y": "●", "P": "◐"}


def main() -> None:
    corpus = json.loads(SOURCE.read_text(encoding="utf-8"))
    entries = corpus["entries"]
    caps = corpus["capabilities"]
    OUT_MD.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        "| System | Type | Coverage | Horizon | " + " | ".join(LABELS[c] for c in caps) + " |",
        "| --- | --- | --- | --- | " + " | ".join("---" for _ in caps) + " |",
    ]
    for e in entries:
        marks = " | ".join(SYMBOL.get(e["caps"].get(c, ""), "·") for c in caps)
        lines.append(f"| **{e['name']}** ({e['year']}) | {e['kind']} | {e['region']} | {e['horizon']} | {marks} |")

    totals = " | ".join(str(sum(1 for e in entries if e["caps"].get(c) in ("Y", "P"))) for c in caps)
    lines.append(f"| **Systems documenting the capability (of {len(entries)})** | | | | {totals} |")

    limitation = [
        "| System | What it provides | What it leaves open |",
        "| --- | --- | --- |",
    ]
    for e in entries:
        provides = e["model"] if e["health"] in ("None", "n/a", "None documented", "None in the paper") else f"{e['model']}. {e['health']}"
        limitation.append(f"| **{e['name']}** | {provides} | {e['limitation']} |")

    OUT_MD.write_text(
        "<!-- generated by src/research/prior_art_tables.py from prior_art.json; do not edit -->\n\n"
        ":::landscape\n\n"
        "### B.2 Capability matrix\n\n"
        f"● documented in the source reviewed · ◐ partial or generic · a dot means *not documented in the source reviewed*, "
        f"which is not a claim of absence. Reviewed {corpus['reviewed_on']}.\n\n"
        + "\n".join(lines)
        + "\n\n:::\n\n### B.3 What each system leaves open\n\n"
        + "\n".join(limitation)
        + "\n",
        encoding="utf-8",
    )

    fields = ["name", "kind", "year", "region", "data", "horizon", "spatial", "model", "health", "performance", "limitation"] + caps + ["url"]
    with OUT_CSV.open("w", newline="", encoding="utf-8-sig") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        for e in entries:
            row = {k: e.get(k, "") for k in fields}
            for c in caps:
                row[c] = e["caps"].get(c, "")
            writer.writerow(row)

    print(f"{len(entries)} systems -> {OUT_MD.relative_to(config.PROJECT_ROOT)}, {OUT_CSV.relative_to(config.PROJECT_ROOT)}")
    for c in caps:
        n = sum(1 for e in entries if e["caps"].get(c) in ("Y", "P"))
        print(f"  {c:22s} {n:2d} / {len(entries)}")


if __name__ == "__main__":
    main()
